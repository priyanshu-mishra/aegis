"""Run the walk-forward with each point model and write docs/POINT_MODELS.md.

Everything downstream of the point forecast (conformal layer, test period, baselines) is
identical across runs, so differences come from the point model alone.

    python scripts/compare_point_models.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from _site_json import write_section
from tabulate import tabulate

from aegis.backtest import run_backtest
from aegis.config import load_config
from aegis.metrics import coverage, diebold_mariano, interval_score, mean_width

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "POINT_MODELS.md"
KINDS = ["har_ols", "ridge", "lightgbm", "mlp"]
LABELS = {
    "har_ols": "HAR regression",
    "ridge": "Ridge (production)",
    "lightgbm": "LightGBM",
    "mlp": "Neural net (5 averaged)",
}
METHODS = {"split_absolute": "Split conformal", "aci": "ACI"}


def main() -> None:
    runs = {}
    for kind in KINDS:
        cfg = load_config(ROOT / "configs/default.yaml", [f"risk.point_model={kind}"])
        runs[kind] = run_backtest(cfg).vol
        print("done", kind)
    cfg = load_config(ROOT / "configs/default.yaml")
    alpha, h = cfg.conformal.alpha, cfg.risk.horizon_days
    ref = runs["ridge"]
    ref_loss = (ref["y"] - ref["mu"]) ** 2

    rows, records = [], []
    for kind in KINDS:
        v = runs[kind]
        loss = (v["y"] - v["mu"]) ** 2
        dm = diebold_mariano(loss.to_numpy(), ref_loss.to_numpy(), lag=h - 1)
        row = [
            LABELS[kind],
            f"{np.sqrt(loss.mean()):.3f}",
            "-" if kind == "ridge" else (f"{dm.p_value:.3f}" if dm.p_value >= 0.001 else "<0.001"),
        ]
        rec = {
            "kind": kind,
            "label": LABELS[kind],
            "rmse": float(np.sqrt(loss.mean())),
            "dm_p": None if kind == "ridge" else dm.p_value,
        }
        for m in METHODS:
            lo, hi, y = v[f"{m}_lo"].to_numpy(), v[f"{m}_hi"].to_numpy(), v["y"].to_numpy()
            rec[m] = {
                "coverage": coverage(y, lo, hi),
                "width": mean_width(lo, hi),
                "winkler": interval_score(y, lo, hi, alpha),
            }
            row += [
                f"{coverage(y, lo, hi):.1%}",
                f"{mean_width(lo, hi):.3f}",
                f"{interval_score(y, lo, hi, alpha):.3f}",
            ]
        rows.append(row)
        records.append(rec)
    head = ["Point model", "RMSE", "DM p vs ridge"]
    for label in METHODS.values():
        head += [f"{label} coverage", "width", "Winkler"]
    table = tabulate(rows, headers=head, tablefmt="github", disable_numparse=True)

    n = len(ref)
    first, last = ref.index[0].date(), ref.index[-1].date()
    OUT.write_text(
        f"""# Point-model comparison

Generated by `python scripts/compare_point_models.py`. Same data, same {n} test days
({first} to {last}), same conformal layer and target level ({1 - alpha:.0%}); only the model
that produces the point forecast of five-day log volatility changes.

{table}

*RMSE*: root-mean-square error of the log-volatility forecast. *DM p*: two-sided
Diebold–Mariano test of equal squared error against ridge, with {h - 1} Newey–West lags because
{h}-day-ahead errors overlap. *Winkler*: interval score (width plus a penalty for misses; lower is
better).

Read it as a test of the claim that a better point forecaster gives tighter intervals at the same
coverage. Coverage should stay near the target for every model, since the conformal layer does not
care how good the forecaster is; width and Winkler show what the forecaster is worth.
"""
    )
    write_section(
        "point_models",
        {"test_days": n, "first_day": str(first), "last_day": str(last), "level": 1 - alpha,
         "rows": records},
    )  # fmt: skip
    print(OUT.read_text())


if __name__ == "__main__":
    main()
