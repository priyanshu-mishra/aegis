"""Does a learned early-warning signal reduce clustered VaR breaches? Writes docs/EARLY_WARNING.md.

Compares ACI with (a) one regime, (b) regimes from current volatility (a non-learned control),
and (c) regimes from a learned stress probability, on the same walk-forward.

    python scripts/early_warning_study.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from _site_json import write_section
from tabulate import tabulate

from aegis.backtest import run_backtest
from aegis.config import load_config
from aegis.data import load_dataset
from aegis.report import var_metrics

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "EARLY_WARNING.md"
METHODS = {
    "aci_var": "ACI, one regime",
    "aci_regime_var": "ACI by current volatility (control)",
    "aci_stress_var": "ACI by learned stress probability",
    "fhs_var": "Filtered historical simulation",
}


def episode_windows(portfolio: pd.Series, train_end: str, quiet: int = 21, days: int = 5):
    """Stress onsets, defined from returns alone (never from any method's output).

    An onset is the first day on which the 5-day RMS return exceeds twice its median over the
    training period, after at least ``quiet`` calm days. The window is the ``days`` days that
    end on the onset: the first days of the shock.
    """
    rms = np.sqrt((portfolio**2).rolling(5).mean())
    thr = 2 * rms.loc[:train_end].median()
    hot = rms > thr
    calm_before = (~hot).rolling(quiet).sum().shift(1) == quiet
    onsets = portfolio.index[(hot & calm_before).to_numpy()]
    return [
        portfolio.index[
            max(portfolio.index.get_loc(d) - days + 1, 0) : portfolio.index.get_loc(d) + 1
        ]
        for d in onsets
    ]


def clustered_share(b: np.ndarray, within: int = 5) -> float:
    """Share of breaches followed by another breach within ``within`` days."""
    idx = np.flatnonzero(b)
    if len(idx) == 0:
        return float("nan")
    return float(np.mean([np.any((idx > i) & (idx <= i + within)) for i in idx]))


def main() -> None:
    cfg = load_config(ROOT / "configs/default.yaml", ["conformal.early_warning=true"])
    ds = load_dataset(cfg)
    res = run_backtest(cfg, dataset=ds)
    ew = res.info["early_warning"]
    windows = [
        w
        for w in episode_windows(ds.market.portfolio, str(cfg.splits.train_end))
        if w[0] > res.vol.index[0]
    ]
    n_days = sum(len(w) for w in windows)

    sections, levels = [], {}
    for a in cfg.conformal.var_alphas:
        df = res.var[a]
        met = var_metrics(df, a)
        in_ep = df.index.isin(np.concatenate([w.to_numpy() for w in windows])) if windows else None
        rows, recs = [], []
        for m, label in METHODS.items():
            b = (df["r_next"] < df[m]).to_numpy()
            ep = int(b[in_ep].sum()) if in_ep is not None else 0
            k = met[m]
            recs.append(
                {
                    "method": m,
                    "label": label,
                    "breach_rate": k["breach_rate"],
                    "kupiec_p": k["kupiec_p"],
                    "christoffersen_p": k["christoffersen_p"],
                    "clustered_share": clustered_share(b),
                    "episode_breaches": ep,
                    "mean_var": k["mean_var"],
                }
            )
            rows.append(
                [
                    label,
                    f"{k['breach_rate']:.2%}",
                    f"{k['kupiec_p']:.3f}",
                    f"{k['christoffersen_p']:.3f}",
                    f"{clustered_share(b):.0%}",
                    f"{ep}",
                    f"{k['mean_var']:.2%}",
                ]
            )
        head = [
            "Method",
            "Breach rate",
            "Kupiec p",
            "Christoffersen p",
            "Followed by another breach within 5 days",
            f"Breaches in first 5 days of {len(windows)} episodes",
            "Mean VaR",
        ]
        table = tabulate(rows, headers=head, tablefmt="github", disable_numparse=True)
        levels[f"{a:g}"] = recs
        sections.append(f"### {(1 - a):.0%} VaR (target breach rate {a:.0%})\n\n{table}\n")

    write_section(
        "early_warning",
        {
            "auc_cal": ew["auc_cal"],
            "auc_test": ew["auc_test"],
            "base_rate_train": ew["base_rate_train"],
            "episodes": len(windows),
            "episode_days": n_days,
            "levels": levels,
        },
    )
    OUT.write_text(
        f"""# Early-warning study (extension B)

Generated by `python scripts/early_warning_study.py`. Same data, same {len(res.vol)} test days
({res.vol.index[0].date()} to {res.vol.index[-1].date()}), same ACI step size and floor.

**The signal.** A logistic regression fitted on the training years only, from eight inputs known at
the close of day t (short- against long-run volatility, drawdown, recent jumps, cross-asset
correlation, the VIX, its change, and its premium over the model's own volatility forecast). It
predicts whether any of the next five days breaches a Gaussian 99% VaR; that happened in
{ew["base_rate_train"]:.0%} of training windows. **AUC {ew["auc_cal"]:.2f} on the calibration years
and {ew["auc_test"]:.2f} on the test years** (0.5 is a coin flip).

**How it is used.** Days are sorted into three regimes by terciles of the signal (thresholds from
the calibration years), and ACI runs separately inside each regime. The control sorts days by
current volatility instead, so any gain from the learned signal has to beat a simple regime label.

{chr(10).join(sections)}

*Episodes* are {len(windows)} stress onsets, defined from returns alone before any method was
compared: the first day the 5-day RMS return exceeds twice its training-period median after 21
calm days; the window is the five days ending on that day ({n_days} days in all). With so few
episodes, differences of one or two breaches are noise. *Mean VaR* is the average size of the loss
limit, a proxy for the capital the method ties up.
"""
    )
    print(OUT.read_text())


if __name__ == "__main__":
    main()
